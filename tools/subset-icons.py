# Makes the OSDs' icon font: Google's Material Icons cut down to the icons
# below, and inc/overlay_icons.h with a #define for each (its UTF-8).
#
#   python -I tools/subset-icons.py MaterialIcons-Regular.ttf MaterialIcons-Regular.codepoints
#
# The two files are font/MaterialIcons-Regular.* in
# https://github.com/google/material-design-icons (Apache License 2.0);
# third_party/fonts/README.md says which version. Needs fontTools
# (pip install fonttools). Add an icon here, run this again, and use its
# ICON_ name in src/overlay.cpp.

import os
import sys

from fontTools import subset

ICONS = """
    desktop_windows image palette timer layers tune build keyboard
    fullscreen photo_size_select_large open_with web_asset open_in_full save memory
    speed sync av_timer mouse
    gradient aspect_ratio grid_on crop_free
    tonality tv brightness_6 contrast exposure thermostat brightness_medium color_lens
    filter_b_and_w invert_colors brightness_low
    code text_fields folder
    insights format_size notes picture_in_picture opacity
    visibility_off slow_motion_video timelapse hourglass_bottom fullscreen_exit
    developer_board view_list filter_none center_focus_strong colorize
    lock_open photo_camera settings
    close chevron_right check restart_alt unfold_more help_outline
""".split()

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_FONT = os.path.join(ROOT, "third_party", "fonts", "material-icons", "MaterialIcons-Subset.ttf")
OUT_HEADER = os.path.join(ROOT, "inc", "overlay_icons.h")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__ or "usage: subset-icons.py font.ttf font.codepoints")

    font_path, codepoints_path = sys.argv[1], sys.argv[2]
    codepoints = {}

    with open(codepoints_path, encoding="ascii") as f:
        for line in f:
            name, _, code = line.strip().partition(" ")
            codepoints.setdefault(name, int(code, 16))

    missing = [n for n in ICONS if n not in codepoints]

    if missing:
        sys.exit("not in the font: " + ", ".join(missing))

    used = sorted({codepoints[n] for n in ICONS})

    options = subset.Options()
    options.layout_features = []  # no ligatures: the OSD uses the codepoints
    options.name_IDs = ["*"]      # keep the copyright and licence names
    options.notdef_outline = True

    font = subset.load_font(font_path, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=used)
    subsetter.subset(font)
    os.makedirs(os.path.dirname(OUT_FONT), exist_ok=True)
    subset.save_font(font, OUT_FONT, options)

    lines = [
        "/* Generated by tools/subset-icons.py: the icons in",
        " * third_party/fonts/material-icons/MaterialIcons-Subset.ttf, as UTF-8 */",
        "",
        "#ifndef OVERLAY_ICONS_H",
        "#define OVERLAY_ICONS_H",
        "",
        "#define ICON_FIRST 0x%04X" % used[0],
        "#define ICON_LAST 0x%04X" % used[-1],
        "",
    ]

    for name in ICONS:
        utf8 = "".join("\\x%02x" % b for b in chr(codepoints[name]).encode("utf-8"))
        lines.append('#define ICON_%s "%s"' % (name.upper(), utf8))

    lines += ["", "#endif", ""]

    with open(OUT_HEADER, "w", newline="\r\n") as f:
        f.write("\n".join(lines))

    print("%d icons, %d bytes" % (len(ICONS), os.path.getsize(OUT_FONT)))


if __name__ == "__main__":
    main()
